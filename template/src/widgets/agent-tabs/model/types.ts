/**
 * Что можно делать с агентом на вкладках. Права считает экран: на экране
 * агента — права раздела агентов, на экране узла — ещё и права узла.
 */
export interface IAgentTabsAccess {
  /** Перезапуск и обновление воркеров. */
  canManage: boolean;
  /** Значения настроек воркеров: просмотр, запись и удаление. */
  canConfig: boolean;
  /** Запросы к воркерам (вкладка «Запрос»). */
  canFetch: boolean;
  /** Журнал агента и воркеров с узла. */
  canLogs: boolean;
}
