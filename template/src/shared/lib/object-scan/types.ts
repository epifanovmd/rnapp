/** Обнаруженный объект для JS-потребителя */
export interface IDetectedObjectInfo {
  /** Индекс класса модели; -1 — класс не сопоставлен индексу */
  classIndex: number;
  /** Имя класса модели; пустая строка — модель имён не содержит */
  className: string;
  /** Подпись для показа: заданная потребителем, имя класса или "#<индекс>" */
  label: string;
  score: number;
}
