import { z } from "zod";

/**
 * Русские стандартные сообщения Zod («Неверный ввод: ожидалось число…»)
 * вместо английских — для полей без своего текста ошибки. Вызывается один
 * раз при старте приложения и в настройке тестов.
 */
export const applyZodLocale = (): void => {
  z.config(z.locales.ru());
};
