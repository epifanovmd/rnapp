/**
 * Короткий уникальный id без внешних зависимостей — для мест, которым не
 * нужна криптографическая стойкость или глобальная уникальность (например,
 * id тоста), только не совпадать с другими id в рамках текущей сессии.
 */
export const createRandomId = (): string =>
  `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;
