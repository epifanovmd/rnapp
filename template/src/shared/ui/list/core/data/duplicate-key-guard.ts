/**
 * Диагностика повторяющихся ключей.
 *
 * Зачем нужна: размеры, позиции и контейнеры адресуются ключом, поэтому два
 * элемента с одним ключом делят одну ячейку. Она отрисовывается на месте
 * первого из них, а на месте второго остаётся дыра — и никакой ошибки при этом
 * не возникает, список просто выглядит сломанным.
 *
 * Какую проблему решает: находит причину до того, как её начнут искать в
 * раскладке. Сообщение выводится один раз на ключ — иначе вывод забьётся
 * повтором на каждом обновлении данных, а обновлений при скролле десятки в
 * секунду.
 */
export class DuplicateKeyGuard {
  /** Ключи, о повторе которых уже сообщено. */
  private readonly reported = new Set<string>();
  /** Ключи, встреченные в текущем проходе по данным. */
  private seen = new Set<string>();

  /** Начать проход по данным: набор встреченных ключей сбрасывается. */
  beginPass(): void {
    this.seen = new Set();
  }

  /** Проверить очередной ключ прохода и сообщить о первом его повторе. */
  check(key: string, index: number): void {
    if (this.seen.has(key)) this.report(key, index);

    this.seen.add(key);
  }

  private report(key: string, index: number): void {
    if (this.reported.has(key)) return;

    this.reported.add(key);
    console.warn(
      `[List] keyExtractor вернул повторяющийся ключ "${key}" на индексе ${index}. ` +
        "Элементы с одинаковым ключом делят контейнер: второй не отрисуется.",
    );
  }
}
